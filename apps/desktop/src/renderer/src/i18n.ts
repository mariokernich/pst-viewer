let current: Messages = de
let currentLocale: 'de' | 'en' = 'de'
let currentFormatLocale = 'de'
let pluralRules = new Intl.PluralRules('de')
let numberFormat = new Intl.NumberFormat('de')

export function setLocale(locale: 'de' | 'en', formatLocale: string = locale): void {
  currentLocale = locale
  current = locale === 'de' ? de : en
  try {
    currentFormatLocale = Intl.getCanonicalLocales(formatLocale)[0] ?? locale
  } catch {
    currentFormatLocale = locale
  }
  pluralRules = new Intl.PluralRules(locale)
  numberFormat = new Intl.NumberFormat(currentFormatLocale)
  document.documentElement.lang = locale
}

/** UI language. */
export function locale(): 'de' | 'en' {
  return currentLocale
}

/** Locale for formatting dates and numbers. */
export function formatLocale(): string {
  return currentFormatLocale
}

export function messages(): Messages {
  return current
}

function interpolate(template: string, params?: Record<string, string | number>): string {
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (_, key: string) => {
    const value = params[key]
    if (value === undefined) return `{${key}}`
    return typeof value === 'number' ? numberFormat.format(value) : value
  })
}

export function t(key: StringKey, params?: Record<string, string | number>): string {
  return interpolate(current[key], params)
}

export function tp(key: PluralKey, count: number): string {
  const forms = current[key]
  const form = pluralRules.select(count) === 'one' ? forms.one : forms.other
  return interpolate(form, { count })
}

export function errorMessage(code: PstErrorCode): string {
  return t(`error_${code}` as StringKey)
}

export function kindLabel(kind: ItemKind, single = false): string {
  return t(`${single ? 'kindSingle' : 'kind'}_${kind}` as StringKey)
}

export function specialFolderName(special: SpecialFolder): string {
  return t(`special_${special}` as StringKey)
}

export function dateGroupLabel(group: DateGroup): string {
  if (group.kind === 'month') {
    const now = new Date()
    const options: Intl.DateTimeFormatOptions = group.year === now.getFullYear() ? { month: 'long' } : { month: 'long', year: 'numeric' }
    return new Intl.DateTimeFormat(currentFormatLocale, options).format(new Date(group.year, group.month - 1, 1))
  }
  return t(`group_${group.kind}` as StringKey)
}
